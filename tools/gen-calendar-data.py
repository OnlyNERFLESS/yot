def esc(v):
    return "'" + v.replace('\\', '\\\\').replace("'", "\\'") + "'"


def rows(cal, hol):
    """Fixed events as [month, day, holiday?1:0, en, fa]; holidays replace any duplicate on the day."""
    seen_hol = set()
    res = []
    for e in raw[cal]:
        if e['type'] != 'fixed':
            continue
        key = (e['month'], e['day'])
        if key in hol and e.get('isHolidayInIran'):
            continue  # the official holiday entry below names the day
        en, fa = e['title']['en'].strip(), e['title']['fa'].strip()
        res.append((key[0], key[1], 0, en, fa))
    for key, (en, fa) in hol.items():
        res.append((key[0], key[1], 1, en, fa))
    res.sort(key=lambda r: (r[0], r[1], -r[2]))
    return res


def emit(name, rs):
    lines = ',\n'.join(f'  [{m}, {d}, {h}, {esc(en)}, {esc(fa)}]' for m, d, h, en, fa in rs)
    return f'export const {name}: Row[] = [\n{lines},\n];\n'


def relatives():
    out = []
    for cal in ('jalali', 'hijri', 'gregorian'):
        for e in raw[cal]:
            if e['type'] != 'relative':
                continue
            r = e['rule']
            which = 'easter' if r['base'] == 'computus' else r['occurrence']
            out.append(f"  [{esc(cal)}, {r.get('month', 0)}, {r.get('weekday', 0)}, {esc(which)}, {esc(e['title']['en'].strip())}, {esc(e['title']['fa'].strip())}],")
    return chr(10).join(out)


start = int(table[0].split()[1])
years = []
for line in table[1:]:
    m = re.match(r"\s*(\d+): '([01]{1,12})',", line)
    years.append((int(m.group(1)), m.group(2)))

