/** One line describing a step, in the UI language. Online providers'
 * own sentences are used when they match the UI language (Neshan's are Persian). */
export function instruction(lang: Lang, s: Step, provider: string): string {
  if (s.instruction && ((provider === 'neshan' && lang === 'fa') || provider === 'google')) return s.instruction;
  const name = lang === 'en' ? s.name_en || s.name : s.name;
  if (s.kind === 'depart') return lang === 'fa' ? `حرکت${name ? ` در ${name}` : ''}` : `Head out${name ? ` on ${name}` : ''}`;
  if (s.kind === 'arrive') return lang === 'fa' ? 'به مقصد رسیدید' : 'You have arrived';
  if (s.kind === 'roundabout') return lang === 'fa' ? `وارد میدان شوید${name ? ` به سمت ${name}` : ''}` : `Enter the roundabout${name ? ` toward ${name}` : ''}`;
  const verb = (lang === 'fa' ? turnFa : turnEn)[s.modifier];
  if (!name) return verb;
  return lang === 'fa' ? `${verb} به ${name}` : `${verb} onto ${name}`;
}

/** List separator. The middle dot reads as the Persian zero (۰), so Persian uses its comma. */
export function sep(lang: Lang): string {
  return lang === 'fa' ? '، ' : ' · ';
}

/** A moment in the UI language: Persian calendar and digits in fa, en-GB order in en. */
export function fmtDateTime(lang: Lang, ms: number): string {
  return new Date(ms).toLocaleString(lang === 'fa' ? 'fa-IR' : 'en-GB', {
    day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
  });
}

