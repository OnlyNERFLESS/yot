export const dict: Record<Lang, Record<Key, string>> = { en, fa };

export function nf(lang: Lang, n: number, digits = 0): string {
  return new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US', { maximumFractionDigits: digits }).format(n);
}

export function fmtDistance(lang: Lang, m: number): string {
  if (m < 950) return `${nf(lang, Math.round(m / 10) * 10)} ${lang === 'fa' ? 'متر' : 'm'}`;
  return `${nf(lang, m / 1000, m < 10_000 ? 1 : 0)} ${lang === 'fa' ? 'کیلومتر' : 'km'}`;
}

export function fmtDuration(lang: Lang, s: number): string {
  const min = Math.max(1, Math.round(s / 60));
  if (min < 60) return `${nf(lang, min)} ${lang === 'fa' ? 'دقیقه' : 'min'}`;
  const h = Math.floor(min / 60);
  const r = min % 60;
  return lang === 'fa' ? `${nf(lang, h)} ساعت و ${nf(lang, r)} دقیقه` : `${h} h ${r} min`;
}

export function fmtClock(lang: Lang, secondsFromNow: number): string {
  const d = new Date(Date.now() + secondsFromNow * 1000);
  return d.toLocaleTimeString(lang === 'fa' ? 'fa-IR' : 'en-GB', { hour: '2-digit', minute: '2-digit' });
}

