/** Plain words for a raw OSM tag such as "highway=tertiary". */
export function kindLabel(lang: Lang, kind: string): string {
  const pick = (v: [string, string]) => (lang === 'fa' ? v[1] : v[0]);
  const exact = KINDS[kind];
  if (exact) return pick(exact);
  const fam = FAMILY[kind.split('=')[0]];
  return fam ? pick(fam) : lang === 'fa' ? 'مکان' : 'Place';
}

/** Plain-language message for a routing or lookup failure; the raw text stays for "Details". */
export function humanError(lang: Lang, raw: string): string {
  const d = dict[lang];
  const m = raw.toLowerCase();
  if (/network|fetch|timeout|abort|offline|internet/.test(m)) return d.errNoInternet;
  if (m.includes('no offline map covers')) return d.errOutsideMap;
  if (m.includes('not near a usable road')) return d.errNoRoad;
  if (m.includes('no route')) return d.errNoRoute;
  return d.errGeneric;
}

/** A due date the way people read it: "Mon 24 Nov" / Persian calendar. */
export function fmtDay(lang: Lang, iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(lang === 'fa' ? 'fa-IR' : 'en-GB', { weekday: 'short', day: 'numeric', month: 'short' });
}
